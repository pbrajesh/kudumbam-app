-- 001: the single-tree schema (21 Oct 2026). Written with "if not exists" so databases created before
-- numbered migrations existed are adopted as-is. Never edit an applied migration; add a new file.

create table if not exists people (
  id            text primary key check (id ~ '^[A-Za-z0-9_]{1,20}$'),
  seq           bigint generated by default as identity,   -- display order (file order, then creation order)
  given         text not null default '',
  surname       text not null default '',
  married_name  text not null default '',
  sex           char(1) not null default 'U' check (sex in ('M', 'F', 'U')),
  birth_date    text not null default '',
  birth_place   text not null default '',
  deceased      boolean not null default false,
  death_date    text not null default '',
  death_place   text not null default '',
  notes         text not null default '',
  extra         jsonb not null default '[]',               -- GEDCOM sub-records the editor does not handle
  version       integer not null default 1,
  updated_by    text,
  updated_at    timestamptz not null default now()
);

create table if not exists families (
  id             text primary key check (id ~ '^[A-Za-z0-9_]{1,20}$'),
  seq            bigint generated by default as identity,
  husband_id     text references people(id) on delete set null,
  wife_id        text references people(id) on delete set null,
  marriage_date  text not null default '',
  marriage_place text not null default '',
  is_current     boolean,                                  -- null: no _CURRENT tag in the file
  extra          jsonb not null default '[]',
  version        integer not null default 1,
  updated_by     text,
  updated_at     timestamptz not null default now()
);

create table if not exists family_children (
  family_id text not null references families(id) on delete cascade,
  person_id text not null references people(id) on delete cascade,
  position  integer not null,
  primary key (family_id, person_id)
);
create index if not exists family_children_person_idx on family_children (person_id);

create table if not exists members (
  id               bigint generated always as identity primary key,
  email            text not null unique check (email = lower(email)),
  supabase_user_id uuid unique,                            -- filled in on first sign-in
  role             text not null check (role in ('viewer', 'editor')),
  created_at       timestamptz not null default now()
);

-- Small key/value settings: file name and GEDCOM submitter of the last import.
create table if not exists tree_meta (
  key   text primary key,
  value text not null
);
